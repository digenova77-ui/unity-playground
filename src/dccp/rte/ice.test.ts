import assert from 'node:assert/strict'
import { test } from 'node:test'
import { answerIce, iceAudit, iceRoom, resetIce } from './ice.ts'

test('any cut is a look at the one ice room, and every look stays on the audit', () => {
  resetIce()
  const before = iceAudit().length
  const all = iceRoom('land as a coach on the hockey rink, all ages, all levels')
  assert.equal(all?.title, 'Ice')
  assert.match(all!.lines.join(' '), /All ages, all levels/)
  assert.match(all!.lines.join(' '), /U16 AAA/)
  assert.match(all!.lines.join(' '), /Ice time/)
  const pp = iceRoom('check out the power play stats')
  assert.equal(pp!.title, 'Ice')
  assert.match(pp!.lines.join(' '), /Chances on the power play/)
  assert.doesNotMatch(pp!.lines.join(' '), /Ice time/)
  assert.match(pp!.speech, /as soon as it's available/)
  const youth = iceRoom('u6 aaa power play')
  assert.match(youth!.speech, /U6 AAA/)
  assert.match(youth!.speech, /U16 AAA/)
  assert.doesNotMatch(youth!.speech, /will not draw/)
  assert.equal(iceAudit().length, before + 3)
  assert.equal(iceAudit().at(-1)?.cut, 'U6 AAA')
  const room = iceRoom('aaa dressing room', { kcal: 400, protein: 30 })
  assert.equal(room?.place, 'dressing')
  assert.match(room!.speech, /400 kcal/)
  const office = iceRoom('aaa board office')
  assert.equal(office?.place, 'office')
  assert.match(office!.speech, /no budget/i)
  const other = iceRoom('aaa penalty box')
  assert.equal(other?.place, 'rink')
  assert.match(other!.speech, /not drawn/)
})

test('a U16 team opens your questions and his, and a name is not stored', () => {
  resetIce()
  const room = iceRoom("my son's u16 hockey team")
  assert.match(room!.speech, /U16 AAA/)
  assert.match(room!.speech, /Which club/)
  assert.match(room!.speech, /On his Unity ID: forward/)
  assert.match(room!.speech, /APIv3 is the seat bind/)
  assert.match(room!.lines.join(' '), /roster is not drawn/)
  const cached = iceRoom('u16 aaa hockey', undefined, [{ name: 'Practice', start: '2026-10-06T18:00:00', location: 'Quinte Sports', opponent: '' }])
  assert.match(cached!.speech, /Practice/)
  assert.match(cached!.speech, /roster is not drawn/)
  const named = answerIce('the club is quinte')
  assert.match(named!.lines.join(' '), /quinte/)
  const position = answerIce('he is a forward and shoots left')
  assert.match(position!.speech, /Are you the parent/)
  assert.doesNotMatch(position!.lines.join(' '), /forward is a name/)
  const drawn = iceRoom('draw the 1-2-2 forecheck')
  assert.equal(drawn?.spots?.length, 5)
  assert.match(drawn!.speech, /not a stat/)
  assert.match(drawn!.speech, /not prescribed/)
  const open = iceRoom('what should we do on the power play')
  assert.equal(open?.spots, undefined)
  assert.match(open!.speech, /not prescribed/)
  resetIce()
  const style = iceRoom('he is a sniper')
  assert.equal(style?.spots?.length, 1)
  assert.match(style!.lines.join(' '), /His style Sniper/)
  const list = iceRoom('what kind of left winger')
  assert.equal(list?.spots, undefined)
  assert.match(list!.speech, /Playmaker/)
  assert.match(list!.speech, /None is assigned/)
  const board = iceRoom('draw the 1-2-2 against their umbrella')
  assert.equal(board?.spots?.length, 5)
  assert.equal(board?.chalk?.length, 5)
  assert.match(board!.speech, /not a scouting report/)
  const scout = iceRoom('what should we do against barrie')
  assert.match(scout!.speech, /Held games 0/)
  assert.match(scout!.speech, /Standings are not held/)
  assert.equal(scout?.chalk, undefined)
})
