import assert from 'node:assert/strict'
import test from 'node:test'
import { coinLine, coinSecurity, coinWords, executeCoins, moveCoin, protocolCost } from './coins.ts'
import { COSMOGENESIS_SEED, TWO_FIFTH } from '../pipe/chain.ts'

test('the coins do not move, and eFuse is named only on the pilot pipe', () => {
  const open = executeCoins(null)
  assert.equal(open.bound, false)
  assert.equal(open.listed, false)
  assert.equal(open.network, false)
  assert.equal(open.till, 'closed')
  assert.equal(open.efuse.named, false)
  assert.equal(open.merit.named, false)
  assert.equal(open.efuse.moves, false)
  assert.equal(executeCoins('david').bound, false)
  const seated = executeCoins('unity:pilot.abc')
  assert.equal(seated.bound, true)
  assert.equal(seated.identity, 'unity:pilot.abc')
  assert.equal(seated.efuse.feeHalf, 0.05)
  assert.equal(seated.efuse.pipe, null)
  assert.equal(seated.efuse.named, false)
  assert.equal(seated.efuse.moves, false)
  assert.equal(seated.merit.named, true)
  const fused = executeCoins('unity:pilot.' + 'ab'.repeat(TWO_FIFTH / 2))
  assert.equal(fused.efuse.pipe, 'pilot')
  assert.equal(fused.efuse.named, true)
  assert.equal(fused.efuse.moves, false)
  assert.equal(fused.till, 'closed')
  assert.equal(seated.unity.moves, false)
  assert.equal(seated.listed, false)
  assert.match(coinWords(null), /\$0/)
  assert.match(coinWords(null), /risk is 0/)
  assert.match(coinWords(null), /not a sale/)
  assert.match(coinWords('unity:pilot.abc'), /This seat is unity:pilot\.abc/)
  assert.match(coinLine(null), /none is seated/)
  const security = coinSecurity()
  assert.equal(security.password, false)
  assert.equal(security.holds, 'nothing')
  assert.equal(security.rings, 3)
  assert.equal(security.seed, COSMOGENESIS_SEED)
  assert.equal(executeCoins(null).security.password, false)
  assert.match(coinWords(null), /three rings and the one seed/)
  assert.match(coinWords(null), /not a password/)
  assert.equal(moveCoin('Merit').ok, true)
  assert.equal(moveCoin('eFuse').ok, false)
  assert.equal(moveCoin('Unity').ok, false)
  const cost = protocolCost()
  assert.equal(cost.supercomputer, false)
  assert.equal(cost.pi, false)
  assert.equal(cost.solar, false)
  assert.equal(cost.geothermal, false)
  assert.equal(cost.wind, false)
  assert.equal(cost.magnetism, false)
  assert.equal(cost.joules, null)
  assert.equal(executeCoins(null).protocol.watts, null)
  assert.match(coinWords(null), /not a supercomputer/)
  assert.match(coinWords(null), /joule stays empty/)
})
