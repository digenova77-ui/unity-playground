import assert from 'node:assert/strict'
import test from 'node:test'
import { admitBody, clearIdempotency } from '../origin/idempotency.ts'
import { bindPurity, breath, elevationWords, purityLoopWords, purityToSign, resetPurity, runPulse, shortPurity, signable, tickPurity } from './purity.ts'

test('the four pillars pulse together and a repeat is not stored', () => {
  resetPurity()
  const first = runPulse({ agreed: false, sensesLive: false })
  assert.equal(first.pillars.NO_FORCE, true)
  assert.equal(first.pillars.HOST_SAFE, true)
  assert.equal(first.pillars.TRUTH_OR_NOTHING, true)
  assert.equal(first.pillars.CLEANUP_FIRST, true)
  assert.equal(first.system, false)
  assert.equal(first.umpires.length, 3)
  assert.equal(runPulse({ agreed: false, sensesLive: false }).duplicate, true)
  const forced = runPulse({ agreed: false, sensesLive: true })
  assert.equal(forced.pillars.NO_FORCE, false)
  assert.match(purityLoopWords(forced), /NO_FORCE fails/)
  assert.match(purityLoopWords(forced), /Every tick/)
  bindPurity(() => ({ agreed: true, sensesLive: true }))
  clearIdempotency()
  assert.equal(tickPurity().pillars.NO_FORCE, true)
  const again = admitBody({ pillars: tickPurity().pillars })
  assert.equal(again.ok && again.replay, true)
  assert.deepEqual(breath(false, false), { inhale: 0, exhale: 0, held: true })
  assert.deepEqual(breath(true, true), { inhale: 1, exhale: 0, held: true })
  assert.deepEqual(breath(true, false), { inhale: 1, exhale: 1, held: false })
  const held = runPulse({ agreed: true, sensesLive: false })
  assert.equal(signable(held), true)
  assert.match(shortPurity(held), /Purity holds/)
  assert.match(purityToSign(held), /NO_FORCE=hold/)
  assert.match(purityToSign(held), /CLEANUP_FIRST=hold/)
  assert.equal(signable(forced), false)
  assert.match(shortPurity(forced), /NO_FORCE/)
  const lie = runPulse({ agreed: true, sensesLive: false, claim: 'The nerve is lit.', held: 'The nerve is not lit.' })
  assert.equal(lie.pillars.TRUTH_OR_NOTHING, false)
  assert.match(shortPurity(lie), /TRUTH_OR_NOTHING/)
  const open = runPulse({ agreed: true, sensesLive: false, claim: 'The nerve is not lit.', held: null })
  assert.equal(open.pillars.TRUTH_OR_NOTHING, false)
  const truth = runPulse({ agreed: true, sensesLive: false, claim: 'The nerve is not lit.', held: 'The nerve is not lit.' })
  assert.equal(truth.pillars.TRUTH_OR_NOTHING, true)
  assert.match(elevationWords(null, 'none'), /has not pulsed/)
  assert.match(elevationWords(forced, 'reading'), /not signed/)
  assert.match(elevationWords(held, 'none'), /are not signed/)
  assert.match(elevationWords(held, 'reading'), /seat was not passed/)
  assert.match(elevationWords(held, 'nonce'), /not that signature yet/)
})
