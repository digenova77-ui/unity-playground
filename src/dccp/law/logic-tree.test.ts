import assert from 'node:assert/strict'
import test from 'node:test'
import { logicTree, logicWords, placeOf, placedIn, treeSeed, seedWords, scaleAll, scaleWords, synapseMap, deviation, withinTolerance, TOLERANCE, mechanism, span, star, insulaWire, connectInsula } from './logic-tree.ts'

test('only a line in the root is attached, and the world is not a branch', () => {
  assert.deepEqual(logicTree(), { root: 9, trunk: 4, hung: 13, open: 8 })
  assert.equal(placeOf('a dark pixel'), 'trunk')
  assert.equal(placeOf('mankind'), 'open')
  assert.equal(placeOf('a neural network'), null)
  assert.match(placedIn('where is mankind') ?? '', /open joint/)
  assert.match(placedIn('a dark pixel') ?? '', /trunk/)
  assert.equal(placedIn('a neural network'), null)
  assert.equal(treeSeed().network, null)
  assert.equal(treeSeed().trunk, 13)
  assert.match(seedWords(), /did not grow/)
  assert.deepEqual(scaleAll(10), { factor: 1, moved: false, trunk: 13, open: 8 })
  assert.match(scaleWords(), /was not lifted/)
  assert.equal(synapseMap().network, null)
  assert.equal(synapseMap().factor, 1)
  assert.deepEqual({ trunk: synapseMap().trunk, open: synapseMap().open }, { trunk: 13, open: 8 })
  assert.equal(placeOf('the insula'), 'open')
  assert.equal(insulaWire().weights, null)
  assert.equal(connectInsula().route, 'feeling-and-phrase')
  assert.equal(connectInsula().pulse, null)
  assert.equal(connectInsula().signal, null)
  assert.equal(connectInsula().implant, null)
  assert.equal(TOLERANCE, 0)
  assert.equal(deviation(1), 0)
  assert.equal(deviation(0), 1)
  assert.equal(withinTolerance(1), true)
  assert.equal(withinTolerance(0), false)
  assert.equal(mechanism().body, null)
  assert.equal(mechanism().network, null)
  assert.equal(mechanism().route, 'place')
  assert.equal(span().goodwill, null)
  assert.equal(span().beacon, 'dark pixel')
  assert.equal(star().points, 4)
  assert.equal(star().hexagram, 6)
  assert.equal(star().missing, null)
  assert.match(logicWords(), /not on the tree/)
  assert.match(logicWords(), /open joint is not an invariant/)
})
