import assert from 'node:assert/strict'
import test from 'node:test'
import { readFileSync } from 'node:fs'
import { CHAIN, FILE, FIRST_RECORD, LATER_RECORD, SEATS, SPLIT, bindBeat, closeCircuit, collapse, collar, continueFile, dayResidue, efuse, energySwitch, hookJacket, ignite, isBeat, merit, nextBeat, splitDigest } from './collar.ts'

test('a passphrase digest splits into two halves and the phrase is not in the result', () => {
  const split = splitDigest(`${'ab'.repeat(16)}${'cd'.repeat(16)}`)
  assert.deepEqual(split, { front: 'ab'.repeat(16), back: 'cd'.repeat(16) })
  assert.equal(splitDigest('').refused, 'empty')
  assert.equal(splitDigest('abcd').refused, 'uneven')
  assert.equal(splitDigest('aa'.repeat(32)).refused, 'uneven')
  if (!('front' in split)) return
  assert.equal(JSON.stringify(split).includes('secret'), false)
})

test('two halves collapse into one box and the jacket is the only door', async () => {
  assert.equal(collapse(null, 'b').series, false)
  assert.equal(collapse('a', 'a').series, false)
  const once = collapse('front', 'back')
  const twice = collapse('front', 'back')
  assert.deepEqual(once, twice)
  if (!once.series) return
  assert.equal(once.box, 'efuse|front|back')
  assert.ok(new TextEncoder().encode(once.box).length <= 256)
  const hole = await hookJacket(once.box, async () => new Response(JSON.stringify({ accepted: false }), { status: 503 }))
  assert.deepEqual(hole, { state: 'HOLE', reason: 'REJECTED' })
  const down = await hookJacket(once.box, async () => { throw new Error('down') })
  assert.deepEqual(down, { state: 'HOLE', reason: 'NETWORK' })
  const held = await hookJacket(once.box, async () => new Response(JSON.stringify({ accepted: true }), { status: 200 }))
  assert.deepEqual(held, { state: 'COMMITTED' })
})

test('the hook stays empty until two different halves meet, and the join does not restart the file', () => {
  assert.equal(collar(null, null).hook, 'empty')
  assert.equal(collar('front', null).hook, 'empty')
  assert.equal(collar('same', 'same').hook, 'empty')
  const once = collar('aaaa', 'bbbb')
  const twice = collar('aaaa', 'bbbb')
  assert.equal(once.hook, 'joined')
  assert.deepEqual(once, twice)
  if (once.hook === 'joined') assert.equal(once.sameFile, true)
  const kept = continueFile(12.5)
  assert.equal(kept.time, 12.5)
  assert.equal(kept.restarted, false)
  assert.equal(kept.src, FILE)
})

