test('the old world scatters, and the bind locks to one then two only', () => {
  const bound = bindBeat(CHAIN)
  assert.equal(bound.scattered, true)
  assert.equal(bound.locked, true)
  assert.equal(isBeat(bound.before), false)
  assert.deepEqual(bound.after, bound.after.map((_, i) => i % 2 === 0 ? 1 : 2))
  assert.ok(bound.after.every((n, i) => i === 0 || n === nextBeat(bound.after[i - 1] as 1 | 2)))
  assert.equal(nextBeat(1), 2)
  assert.equal(nextBeat(2), 1)
  assert.equal(nextBeat(nextBeat(1)), 1)
  assert.equal(isBeat([1, 2, 1, 2]), true)
  assert.equal(isBeat([1, 2, 1]), false)
  assert.equal(isBeat([2, 1, 2, 1]), false)
  assert.equal(isBeat([1, 1, 2, 2]), false)
  assert.equal(isBeat([1, 2, 1, 3]), false)
  assert.equal(isBeat([1, 2, 2, 1]), false)
  assert.equal(isBeat([]), false)
  const broken = bound.after.slice()
  broken[2] = 2
  assert.equal(isBeat(broken), false)
  assert.equal(bindBeat([{ n: 1, line: 'no join' }, { n: 2, line: 'still none' }]).locked, false)
  assert.equal(CHAIN.findIndex(row => row.line.startsWith('The eFuse is the join')), CHAIN.findIndex(row => row.half === 'day'))
  assert.ok(CHAIN.slice(0, bound.before.length).every(row => row.half === 'night'))
  assert.ok(CHAIN.slice(bound.before.length).every(row => row.half === 'day'))
  const residue = dayResidue(readFileSync(new URL('../styles/main.css', import.meta.url), 'utf8'))
  assert.deepEqual(residue, { frame: false, pad: false, scaffold: false })
  assert.equal(merit(residue, bound.locked).share, 1)
  assert.equal(merit(residue, false).share, 0)
  assert.equal(merit({ frame: true, pad: false, scaffold: false }, true).share, 0)
  assert.equal(merit({ frame: false, pad: true, scaffold: false }, true).share, 0)
  assert.equal(merit({ frame: false, pad: false, scaffold: true }, true).share, 0)
  assert.equal(merit(dayResidue('.day-half { padding: 18px; border: 0; border-radius: 0; box-shadow: none; transform: none; }'), true).share, 0)
})

test('the receipt DAG is one then two, and the rest of the talk is gone', () => {
  const rises = CHAIN.map(row => row.rise)
  assert.equal(rises[0], 0)
  assert.equal(rises.at(-1), 1)
  assert.ok(rises.every((rise, i) => i === 0 || rise >= rises[i - 1]))
  const night = CHAIN.filter(row => row.half === 'night')
  const day = CHAIN.filter(row => row.half === 'day')
  assert.equal(night.length, day.length)
  assert.equal(CHAIN.findIndex(row => row.half === 'day'), night.length)
  assert.equal(energySwitch(false).id, 'energy')
  assert.equal(energySwitch(false).half, 'night')
  assert.equal(energySwitch(true).half, 'day')
  assert.equal(energySwitch(true).fuse, 'eFuse')
  assert.equal(efuse('a', 'a').joined, false)
  assert.equal(efuse('a', null).joined, false)
  const records = efuse(FIRST_RECORD, LATER_RECORD)
  assert.deepEqual(records, efuse(FIRST_RECORD, LATER_RECORD))
  assert.equal(records.joined, true)
  const text = CHAIN.map(row => row.line).join(' ')
  assert.match(text, /seed is at -1/)
  assert.match(text, /one store/)
  assert.match(text, /Five faces/)
  assert.match(text, /Zenodo 10\.5281\/zenodo\.21940542/)
  assert.match(text, /Zenodo 10\.5281\/zenodo\.21984747/)
  assert.match(text, /The circuit is closed/)
  assert.match(text, /A touch ignites it/)
  const circuit = closeCircuit()
  assert.equal(circuit.closed, true)
  assert.equal(circuit.ignited, false)
  assert.equal(circuit.hashedLater, false)
  assert.equal(ignite(circuit, false).ignited, false)
  assert.equal(ignite(circuit, true).ignited, true)
  assert.match(text, /later file was not hashed here/)
  const idea = text.indexOf('Before there was nothing')
  const loop = text.indexOf('The loop is the ORCID')
  assert.ok(idea >= 0 && loop > idea)
  assert.match(text, /The idea is the seed/)
  const bang = text.indexOf('The bang')
  const stray = text.indexOf('the target walks away')
  const fuse = text.indexOf('The eFuse is the join')
  const economy = text.indexOf('economy of tomorrow')
  const touch = text.indexOf('A touch ignites it')
  assert.ok(bang === 0 && stray > bang && fuse > stray && economy > fuse && touch > economy)
  assert.match(text, /One writes/)
  assert.match(text, /last hash/)
  assert.match(text, /floor of the diamond is zero/)
  assert.equal(/medical|welfare|neurotransmitter|speed of light|black hole|dark energy/i.test(text), false)
})
