import assert from 'node:assert/strict'
import test from 'node:test'
import { admitBody, admitOmni, admitToken, admitTwoRows, admitVultr, attemptKey, clearIdempotency, connectSides, stored, unityIsNotTheKey, vultrBody } from './idempotency.ts'
import { COSMOGENESIS_SEED } from '../pipe/chain.ts'

test('the same body is one row, and a token cannot change bodies', () => {
  clearIdempotency()
  const first = admitBody({ manifest: 'a' })
  const second = admitBody({ manifest: 'a' })
  assert.equal(first.ok && second.ok && first.key === second.key && second.replay, true)
  assert.equal(stored(first.ok ? first.key : '')?.delivered, false)
  const other = admitBody({ manifest: 'b' })
  assert.equal(first.ok && other.ok && first.key !== other.key, true)
  const token = admitToken('caller-1', { manifest: 'c' })
  const again = admitToken('caller-1', { manifest: 'c' })
  assert.equal(token.ok && again.ok && again.replay, true)
  assert.equal(admitToken('caller-1', { manifest: 'd' }).ok, false)
  const drifted = admitBody({ manifest: 'd' })
  assert.equal(drifted.ok && drifted.replay, false)
  const one = attemptKey('seat-a', { act: 1 })
  const two = attemptKey('seat-a', { act: 2 })
  assert.equal(one !== null && two !== null && one !== two, true)
  assert.equal(unityIsNotTheKey().seatAsEveryAct, false)
  assert.equal(unityIsNotTheKey().financial, null)
  assert.equal(admitBody({ private_key: 'no' }).ok, false)
  assert.equal(admitBody({ api_key: 'no' }).ok, false)
  clearIdempotency()
  const vultr = admitVultr()
  const vultrAgain = admitVultr()
  assert.equal(vultr.ok && vultrAgain.ok && vultr.replay === false && vultrAgain.replay === true && vultr.key === vultrAgain.key, true)
  assert.equal(stored(vultr.ok ? vultr.key : '')?.delivered, false)
  assert.equal(admitToken(vultrBody().user, { act: 'destroy', host: 'vultr', user: vultrBody().user }).ok, false)
  clearIdempotency()
  const pay = admitOmni('payer-1', 'finance', 'charge', { unit: 1 })
  const payAgain = admitOmni('payer-1', 'finance', 'charge', { unit: 1 })
  assert.equal(pay.ok && payAgain.ok && pay.replay === false && payAgain.replay && pay.key === payAgain.key, true)
  assert.equal(pay.ok && pay.money === null && pay.settled === false && pay.delivered === false, true)
  assert.equal(admitOmni('payer-1', 'api', 'charge', { unit: 1 }).ok, false)
  assert.equal(admitOmni('payer-1', 'finance', 'charge', { api_key: 'no' }).ok, false)
  assert.equal(admitOmni('', 'page', 'tick', { n: 1 }).ok, false)
  assert.equal(admitTwoRows().ok, false)
  assert.equal(admitTwoRows().stored, 0)
  clearIdempotency()
  assert.equal(connectSides('left', 'left').ok, false)
  assert.equal(connectSides('', 'right').ok, false)
  const joined = connectSides('serial', 'parallel')
  const joinedAgain = connectSides('shown', 'audit')
  assert.equal(joined.ok && joinedAgain.ok && joined.replay === false && joinedAgain.replay && joined.key === COSMOGENESIS_SEED, true)
  assert.equal(joined.ok && joined.rows === 1 && joined.money === null && joined.delivered === false, true)
  assert.equal(stored(COSMOGENESIS_SEED)?.delivered, false)
  assert.equal(joined.ok && [joined.point.x, joined.point.y, joined.point.z].every(n => n >= -1 && n <= 1), true)
  clearIdempotency()
})
